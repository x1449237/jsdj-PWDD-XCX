package utils

import (
	"strings"
	"unicode"
)

// pinyinFirstLetter 内置常用汉字 -> 拼音首字母映射表
// 覆盖 GB2312 一级常用汉字(3755)的拼音首字母，无第三方依赖
// 多音字采用最常见读音
var pinyinFirstLetter = buildPinyinMap()

// GetPinyinFirstLetters 取中文字符串的拼音首字母(大写)
// 非中文字符保留原字符(字母转大写)，数字与符号丢弃
func GetPinyinFirstLetters(s string) string {
	var b strings.Builder
	for _, r := range s {
		if r >= 0x4E00 && r <= 0x9FA5 {
			// 中文字符
			if letter, ok := pinyinFirstLetter[r]; ok {
				b.WriteByte(letter)
			}
			continue
		}
		// 字母:转大写保留
		if unicode.IsLetter(r) {
			b.WriteRune(unicode.ToUpper(r))
			continue
		}
		// 数字与符号丢弃
	}
	return b.String()
}

// GenerateAbbreviation 根据名称生成 3-6 位大写缩写
// 中文:取拼音首字母大写
// 非中文:取前若干字母大写
// 返回空串表示名称不合法(空白或纯特殊符号)
func GenerateAbbreviation(name string) string {
	name = strings.TrimSpace(name)
	if name == "" {
		return ""
	}
	// 统计有效字符数(字母或中文)
	hasContent := false
	for _, r := range name {
		if unicode.IsLetter(r) || (r >= '0' && r <= '9') {
			hasContent = true
			break
		}
	}
	if !hasContent {
		return ""
	}

	// 判断是否含中文
	hasChinese := false
	for _, r := range name {
		if r >= 0x4E00 && r <= 0x9FA5 {
			hasChinese = true
			break
		}
	}

	var abbr string
	if hasChinese {
		abbr = GetPinyinFirstLetters(name)
	} else {
		// 非中文:仅保留字母数字并转大写
		var b strings.Builder
		for _, r := range name {
			if unicode.IsLetter(r) || (r >= '0' && r <= '9') {
				b.WriteRune(unicode.ToUpper(r))
			}
		}
		abbr = b.String()
	}

	// 截取 3-6 位
	if len(abbr) < 3 {
		// 不足 3 位，用 X 补齐(避免与系统冲突)
		abbr = abbr + strings.Repeat("X", 3-len(abbr))
	}
	if len([]rune(abbr)) > 6 {
		abbr = string([]rune(abbr)[:6])
	}
	return strings.ToUpper(abbr)
}

// buildPinyinMap 构建汉字->首字母映射表
// 按首字母分组，每组列出该首字母对应的常用汉字区间与离散字
func buildPinyinMap() map[rune]byte {
	m := make(map[rune]byte, 4096)
	for letter, chars := range pinyinGroups {
		for _, ch := range chars {
			m[ch] = letter
		}
	}
	return m
}

